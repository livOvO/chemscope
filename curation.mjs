export function autoPaperTitle(titleEn = '') {
  const special = SPECIAL_TITLES.find(([re]) => re.test(titleEn))?.[1];
  if (special) return special;
  const topic = TOPIC_RULES.find(([re]) => re.test(titleEn))?.[1];
  const action = ACTION_RULES.find(([re]) => re.test(titleEn))?.[1];
  if (!topic || !action) return '';
  return `${topic}：${action}`;
}

export function autoNewsTitle(title = '') {
  return String(title)
    .replace(/\s*[|｜]\s*.*$/, '')
    .replace(/^【[^】]+】/, '')
    .trim();
}
